CREATE ROLE rors_owner_grp NOLOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS;
CREATE ROLE rors_runtime_grp NOLOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS;
CREATE ROLE rors_readonly_grp NOLOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS;
CREATE ROLE rors_dba LOGIN NOINHERIT NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS;
GRANT rors_owner_grp TO rors_dba WITH INHERIT FALSE, SET TRUE, ADMIN FALSE;
CREATE ROLE rors_app LOGIN INHERIT NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS;
GRANT rors_runtime_grp TO rors_app WITH INHERIT TRUE, SET TRUE, ADMIN FALSE;
CREATE ROLE rors_report LOGIN INHERIT NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS;
GRANT rors_readonly_grp TO rors_report WITH INHERIT TRUE, SET TRUE, ADMIN FALSE;
CREATE DATABASE mesa_g05_activity4 OWNER rors_owner_grp;
CREATE DATABASE rors_unrelated_lab;
REVOKE ALL ON DATABASE mesa_g05_activity4 FROM PUBLIC;
GRANT CONNECT ON DATABASE mesa_g05_activity4 TO rors_dba,rors_runtime_grp,rors_readonly_grp;
