GRANT boardtrack_runtime_grp TO boardtrack_app WITH INHERIT TRUE, SET TRUE, ADMIN FALSE;
CREATE ROLE boardtrack_report LOGIN INHERIT NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS;
GRANT boardtrack_readonly_grp TO boardtrack_report WITH INHERIT TRUE, SET TRUE, ADMIN FALSE;
CREATE DATABASE boardtrack_g05_activity4 OWNER boardtrack_owner_grp;
CREATE DATABASE boardtrack_unrelated_lab;
REVOKE ALL ON DATABASE boardtrack_g05_activity4 FROM PUBLIC;
GRANT CONNECT ON DATABASE boardtrack_g05_activity4 TO boardtrack_dba,boardtrack_runtime_grp,boardtrack_readonly_grp;
